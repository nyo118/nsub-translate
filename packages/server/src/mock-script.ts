export type ScriptEvent = Omit<TranscriptMessage, 'sessionId'>;

/**
 * Flatten the segments into an ordered list of transcript events.
 * The list is deterministic: same input → same output.
 */
export function buildScriptEvents(segments: readonly MockSegment[] = MOCK_SEGMENTS): ScriptEvent[] {
  const events: ScriptEvent[] = [];
  for (const segment of segments) {
    let revision = 0;
    for (const partial of segment.partials) {
      events.push({
        type: 'transcript',
        segmentId: segment.segmentId,
        revision: revision++,
        status: 'partial',
        startMs: segment.startMs,
        sourceText: partial,
      });
    }
    events.push({
      type: 'transcript',
      segmentId: segment.segmentId,
      revision: revision,
      status: 'final',
      startMs: segment.startMs,
      endMs: segment.endMs,
      sourceText: segment.finalText,
      translatedText: segment.translatedText,
    });
  }
  return events;
}
