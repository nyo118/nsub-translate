import type { TranscriptMessage } from '@lst/protocol';

/**
 * A deterministic subtitle script used by the Phase 0 mock session.
 *
 * Each segment is emitted as a sequence of revisions: growing `partial`
 * revisions (no translation yet), then one `final` revision that carries
 * the translation. This exercises the receiver's segmentId/revision rules.
 */
export interface MockSegment {
  segmentId: string;
  startMs: number;
  endMs: number;
  /** Progressive partial texts, in order. */
  partials: string[];
  finalText: string;
  translatedText: string;
}

